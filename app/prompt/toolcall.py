# 工具调用智能体的基础提示词模板

"""
这个文件定义了工具调用智能体(ToolCallAgent)使用的提示词模板。
这是最基础的提示词设计，其他智能体通常会扩展或修改这些基础提示词。

提示词模板在智能体开发中的作用:
1. 定义智能体的行为边界和能力范围
2. 设置智能体的"性格"和交互风格
3. 提供执行任务所需的上下文信息
4. 指导智能体如何使用可用工具

对于初学者来说，这个文件是理解提示词设计的起点，
展示了最简化的提示词结构。
"""

# 系统提示词: 定义智能体的基本身份和角色
# 这个提示词非常简洁，只告诉LLM它是一个能够执行工具调用的智能体
# 在实际应用中，通常会提供更多具体指导和约束
SYSTEM_PROMPT = "You are an agent that can execute tool calls"

# 下一步提示词: 在每次推理循环中提供给智能体的提示
# 这个提示词提醒智能体如何终止交互，是最基本的操作指导
# 在复杂智能体中，下一步提示词通常会包含更多上下文信息和具体指令
NEXT_STEP_PROMPT = (
    "If you want to stop interaction, use `terminate` tool/function call."
)

# 提示词设计的教学说明:
# 1. 简洁明了: 提示词应当清晰表达目标和约束
# 2. 角色定位: 明确告诉AI它"是什么"(身份)和"能做什么"(能力)
# 3. 行为指导: 提供具体的行为指南和操作流程
# 4. 边界限制: 明确指出不应执行的操作或超出范围的行为
